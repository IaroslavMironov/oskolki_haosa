const fast = process.argv.includes('--fast');
const kind = (m) => (!m.length ? 'text' : m.some((f) => f.endsWith('.mp4')) ? 'video' : m.length > 1 ? 'carousel' : 'image');

db.exec('begin');
run("delete from posts where release='ворожея-демо'");
PLAN.forEach(([at, title, media, targets, caption, note = ''], i) => {
  const id = Number(run('insert into posts (title, kind, caption, media, release, note) values (?,?,?,?,?,?)',
    title, kind(media), caption, JSON.stringify(media), 'ворожея-демо', note).lastInsertRowid);
  // --fast: по посту в минуту, начиная через минуту.
  const when = fast ? new Date(Date.now() + (i + 1) * 60_000).toISOString() : new Date(`${at}:00+03:00`).toISOString();
  for (const t of targets) {
    const [platform, format] = t.replace('!', '').split('/');
    run('insert into targets (post_id, platform, format, planned_at, mode, status, title) values (?,?,?,?,?,?,?)',
      id, platform, format, when, t.endsWith('!') ? 'manual' : 'auto', fast ? 'scheduled' : 'draft', platform === 'youtube' ? `${title} · Осколки хаоса` : null);
  }
});
db.exec('commit');
log(`загружен пробный план «Ворожеи»${fast ? ' (сжатый, сразу в очереди)' : ''}`);
const n = get("select count(*) n from targets t join posts p on p.id=t.post_id where p.release='ворожея-демо'").n;
console.log(`План «Ворожеи»: ${PLAN.length} постов, ${n} публикаций${fast ? ' — в очереди, по посту в минуту' : ' — черновиками'}.`);
